"""How strict should the drift alarm be? Measure false alarms on clean streams.

No drift is simulated here. For every category, clean streams are compared
with a clean reference (same recipe as monitoring/simulate_drift.py, different
images), and each candidate rule is counted: how often would it have raised
the alarm when nothing had changed?

A candidate rule is "at least K of the 19 watched numbers have p below P".
The rule in monitoring/drift.py was chosen from this table.

Needs only models/*/reference.csv, so it runs in a couple of minutes.

    python monitoring/calibrate.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import ks_2samp

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from monitoring.drift import COLUMNS, MIN_DRIFTED, P_VALUE, WINDOW  # noqa: E402
from monitoring.simulate_drift import MAX_STREAM_TRAIN_IMAGES, N_REFERENCE, draw_stream  # noqa: E402

MODELS_ROOT = REPO / "models"
RULES = [(p, k) for p in (0.01, 0.001) for k in (3, 4, 5, 6)]
SPLIT_SEEDS = 3
STREAM_SEEDS = 3
STREAM_LENGTH = 250
STEP = 2


def main() -> None:
    categories = sorted(p.name for p in MODELS_ROOT.iterdir() if (p / "reference.csv").is_file())
    rows = []
    for category in categories:
        table = pd.read_csv(MODELS_ROOT / category / "reference.csv")
        train_good = table[(table["split"] == "train") & (table["label"] == "good")]
        test_good = table[(table["split"] == "test") & (table["label"] == "good")]
        test_defect = table[(table["split"] == "test") & (table["label"] != "good")]
        test_share = len(test_good) / (len(train_good) + len(test_good))
        alarms = dict.fromkeys(RULES, 0)
        windows = 0
        for split_seed in range(SPLIT_SEEDS):
            reference_images: set[str] = set()
            stream_images: set[str] = set()
            for group, cap in ((train_good, MAX_STREAM_TRAIN_IMAGES), (test_good, None), (test_defect, None)):
                shuffled = group.sample(frac=1.0, random_state=split_seed)
                reference_images |= set(shuffled["image"].iloc[: len(shuffled) // 2])
                stream_images |= set(shuffled["image"].iloc[len(shuffled) // 2 :].head(cap))
            reference = draw_stream(table, reference_images, test_share, N_REFERENCE, np.random.default_rng(12345))
            reference_values = {column: reference[column].to_numpy() for column in COLUMNS}
            for stream_seed in range(STREAM_SEEDS):
                stream = draw_stream(table, stream_images, test_share, STREAM_LENGTH, np.random.default_rng(stream_seed))
                stream_values = {column: stream[column].to_numpy() for column in COLUMNS}
                for end in range(WINDOW, STREAM_LENGTH + 1, STEP):
                    p_values = np.array(
                        [
                            ks_2samp(reference_values[column], stream_values[column][end - WINDOW : end]).pvalue
                            for column in COLUMNS
                        ],
                    )
                    windows += 1
                    for p, k in RULES:
                        alarms[(p, k)] += int((p_values < p).sum() >= k)
        rows.append(
            {
                "category": category,
                "good_test_photos": len(test_good),
                "windows": windows,
                **{rule: alarms[rule] for rule in RULES},
            },
        )
        print(f"{category:<11} " + "  ".join(f"{alarms[r] / windows:6.1%}" for r in RULES), flush=True)

    def label(rule: tuple[float, int]) -> str:
        return f"{rule[1]} of {len(COLUMNS)} at p < {rule[0]:g}"

    total_windows = sum(row["windows"] for row in rows)
    lines = [
        "# Drift alarm calibration: false alarms when nothing has changed",
        "",
        "Generated by `monitoring/calibrate.py`. Do not edit by hand.",
        "",
        f"Clean streams against a clean reference, window of {WINDOW} images, {total_windows:,} windows in all. "
        "Each column is one candidate rule; each cell is the share of windows where that rule would have "
        "raised the alarm although nothing had changed.",
        "",
        f"**Rule in use: {label((P_VALUE, MIN_DRIFTED))}.**",
        "",
        "The rule was chosen from this table, so the false-alarm rate reported for it is a calibrated "
        "figure, not an independent test.",
        "",
        "Toothbrush has only 12 good test photos, so 6 per half. The reference half and the stream half "
        "differ by chance, and every rule alarms on it. That is a limit of this experiment on so few "
        "images, not evidence of drift.",
        "",
        "| Category | Good test photos | " + " | ".join(label(rule) for rule in RULES) + " |",
        "|---|---|" + "---|" * len(RULES),
    ]
    for row in rows:
        cells = " | ".join(f"{row[rule] / row['windows']:.1%}" for rule in RULES)
        lines.append(f"| {row['category']} | {row['good_test_photos']} | {cells} |")
    lines.append(
        "| **All** | | "
        + " | ".join(f"**{sum(row[rule] for row in rows) / total_windows:.2%}**" for rule in RULES)
        + " |",
    )
    others = [row for row in rows if row["category"] != "toothbrush"]
    other_windows = sum(row["windows"] for row in others)
    lines.append(
        "| **All but toothbrush** | | "
        + " | ".join(f"**{sum(row[rule] for row in others) / other_windows:.2%}**" for rule in RULES)
        + " |",
    )
    out = REPO / "reports" / "drift_calibration.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[-2:]))
    print(f"\nSaved {out.relative_to(REPO)}")


if __name__ == "__main__":
    main()
