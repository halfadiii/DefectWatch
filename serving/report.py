"""Build reports/serving_models.md from the exported bundles in models/.

    python serving/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def main() -> None:
    metas = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((REPO / "models").glob("*/meta.json"))]
    if not metas:
        raise SystemExit("No exported models. Run serving/export.py first.")

    def mean(key: str) -> float:
        return sum(m[key] for m in metas) / len(metas)

    first = metas[0]
    lines = [
        "# The models the service runs",
        "",
        "Generated by `serving/report.py` from `models/*/meta.json`. Do not edit by hand.",
        "",
        f"PatchCore, {first['backbone']} backbone, coreset {first['coreset_sampling_ratio']:g}, exported to ONNX. "
        "Every number below was measured through ONNX with the service's own image loading, "
        "on MVTec AD's official test split.",
        "",
        "- **Threshold**: an image is called a defect when its score is at or above this. "
        "Tuned for the best F1 on the full test split.",
        "- **Good parts failed / Defects missed**: at that threshold, on the test split.",
        "- **F1 held out**: threshold tuned on half the test images, scored on the other half (10 random halves).",
        "- **Largest score gap**: biggest difference between this ONNX path and PyTorch on any test image. "
        "It comes from resizing with a different library, not from the export.",
        "",
        "| Category | ONNX size | Image AUROC | Threshold | F1 at threshold | F1 held out | "
        "Good parts failed | Defects missed | Largest score gap |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for m in metas:
        good_failed = round(m["good_parts_failed"] * m["n_test_good"])
        missed = round(m["defects_missed"] * m["n_test_defect"])
        lines.append(
            f"| {m['category']} | {m['onnx_mb']} MB | {m['image_auroc']:.4f} | {m['threshold']:.2f} | "
            f"{m['f1_at_threshold']:.4f} | {m['f1_heldout']:.4f} | "
            f"{good_failed} of {m['n_test_good']} | {missed} of {m['n_test_defect']} | "
            f"{m['parity_max_score_gap']:.2f} |",
        )
    total_good = sum(m["n_test_good"] for m in metas)
    total_defect = sum(m["n_test_defect"] for m in metas)
    total_good_failed = sum(round(m["good_parts_failed"] * m["n_test_good"]) for m in metas)
    total_missed = sum(round(m["defects_missed"] * m["n_test_defect"]) for m in metas)
    lines.append(
        f"| **All {len(metas)}** | **{sum(m['onnx_mb'] for m in metas):.0f} MB** | **{mean('image_auroc'):.4f}** | | "
        f"**{mean('f1_at_threshold'):.4f}** | **{mean('f1_heldout'):.4f}** | "
        f"**{total_good_failed} of {total_good}** | **{total_missed} of {total_defect}** | |",
    )
    out = REPO / "reports" / "serving_models.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[-len(metas) - 3 :]))
    print(f"\nSaved {out.relative_to(REPO)}")


if __name__ == "__main__":
    main()
