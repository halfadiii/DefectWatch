"""Build reports/accuracy.md from the runs recorded in MLflow.

MLflow is the record; this only formats it. For each backbone and coreset
setting it takes the newest run per category.

    python training/report.py
"""

from __future__ import annotations

import os
from pathlib import Path

os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")

import mlflow

REPO = Path(__file__).resolve().parents[1]
EXPERIMENT = "defectwatch-patchcore"


def main() -> None:
    if not os.environ.get("MLFLOW_TRACKING_URI"):
        mlflow.set_tracking_uri(f"sqlite:///{(REPO / 'mlflow.db').as_posix()}")
    runs = mlflow.search_runs(experiment_names=[EXPERIMENT], order_by=["attributes.start_time DESC"])
    if runs.empty:
        raise SystemExit("No runs recorded yet. Run training/train.py first.")
    runs = runs[runs["status"] == "FINISHED"]
    runs["config"] = runs["params.backbone"] + ", coreset " + runs["params.coreset_sampling_ratio"]
    latest = runs.drop_duplicates(subset=["config", "params.category"], keep="first")

    lines = [
        "# Detection accuracy on MVTec AD's official test split",
        "",
        "Generated by `training/report.py` from the MLflow runs. Do not edit by hand.",
        "",
        "- **Image AUROC**: how well the score separates good parts from defective ones "
        "(1.0 is perfect, 0.5 is a coin toss). It does not depend on a threshold.",
        "- **F1 held out**: the threshold is tuned on half of the test images and scored on the other half, "
        "averaged over 10 random halves. This is the honest figure.",
        "- **F1 optimistic**: the threshold is tuned on the same images it is scored on. "
        "Shown because papers usually report it this way.",
        "- **Pixel AUROC**: how well the heatmap matches the hand-drawn defect masks.",
        "",
        "MVTec has no separate labelled set to tune a threshold on, which is why both F1 figures are shown.",
        "",
        "Fit times are rough: they include reading the images from disk, and some runs shared the laptop "
        "with other programs.",
        "",
    ]
    summary = ["## Summary", "", "| Model | Categories | Mean image AUROC | Mean F1 held out | Mean F1 optimistic | "
               "Mean pixel AUROC | Mean memory bank | Mean fit time |", "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    details: list[str] = []
    for config, group in sorted(latest.groupby("config"), key=lambda item: -item[1]["metrics.image_auroc"].mean()):
        group = group.sort_values("params.category")
        summary.append(
            f"| {config} | {len(group)} | {group['metrics.image_auroc'].mean():.4f} | "
            f"{group['metrics.f1_heldout'].mean():.4f} | {group['metrics.f1_optimistic'].mean():.4f} | "
            f"{group['metrics.pixel_auroc'].mean():.4f} | {group['metrics.memory_bank_mb'].mean():.0f} MB | "
            f"{group['metrics.fit_seconds'].mean():.0f} s |",
        )
        details += [
            f"## {config}",
            "",
            "| Category | Train images | Test good / defect | Image AUROC | F1 held out | F1 optimistic | "
            "Pixel AUROC | Memory bank | Fit time |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for _, run in group.iterrows():
            details.append(
                f"| {run['params.category']} | {run['params.n_train']} | "
                f"{run['params.n_test_good']} / {run['params.n_test_defect']} | "
                f"{run['metrics.image_auroc']:.4f} | {run['metrics.f1_heldout']:.4f} | "
                f"{run['metrics.f1_optimistic']:.4f} | {run['metrics.pixel_auroc']:.4f} | "
                f"{run['metrics.memory_bank_mb']:.0f} MB | {run['metrics.fit_seconds']:.0f} s |",
            )
        details.append("")

    out = REPO / "reports" / "accuracy.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines + summary + [""] + details), encoding="utf-8")
    print("\n".join(summary[2:]))
    print(f"\nSaved {out.relative_to(REPO)}")


if __name__ == "__main__":
    main()
